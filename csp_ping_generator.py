#!/usr/bin/env python3
"""
csp_ping_generator.py

Wrapper that mimics the SRS-4 debug shell command

    csp ping -c<count> -s200 -q -b -i<interval> -t30 10

but sends the CSP ping packets over UDP to the GNU Radio Socket PDU (Server)
block that feeds the SRS-4 Transmitter's csp_in port.

Only two options are specifiable for now:
    -c COUNT      number of pings to send
    -i INTERVAL   gap between pings (assumed to be MILLISECONDS; lower = faster)

Everything else is fixed (see constants below). Only the COUNT pings are sent:
idle frames are generated by the SRS-4 Transmitter block itself (its
`idleframes` setting), so none are sent from here. No reply is waited for
(nothing answers in the sim).

Usage:
    python csp_ping_generator.py -c 5 -i 100
    python csp_ping_generator.py -c 2000 -i 100
"""
import argparse
import asyncio
import socket

import csp_py
from csp_py.interfaces.serializing_interface import CspSerializingInterface

# ---- GNU Radio side ---------------------------------------------------------
TX_HOST = "127.0.0.1"
TX_PORT = 52003          # Socket PDU (UDP Server) -> SRS-4 Transmitter csp_in

# ---- CSP side (fixed for now) -----------------------------------------------
SRC_ADDR = 24            # the SRS-4's own address (the shell pings *from* it)
DST_ADDR = 10            # the "10" in `csp ping ... 10`
PING_PORT = 1            # CSP ping service port
PAYLOAD_BYTES = 200      # the -s200

_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)


async def capture_frame(frame: bytes) -> None:
    """Called by csp_py for every serialized CSP packet it wants to send."""
    _sock.sendto(frame, (TX_HOST, TX_PORT))


def make_payload(seq: int) -> bytes:
    """4-byte big-endian sequence number + incrementing byte pattern."""
    head = seq.to_bytes(4, "big")
    body = bytes(i % 256 for i in range(PAYLOAD_BYTES - len(head)))
    return head + body


async def main(count: int, interval_ms: float) -> None:
    node = csp_py.CspNode()
    iface = CspSerializingInterface(capture_frame)
    node.router.add_interface(iface, address=SRC_ADDR, netmask_bits=0)  # catch-all
    router_task = asyncio.create_task(node.router.arun())

    connection = await node.connect(dst=DST_ADDR, port=PING_PORT)
    for seq in range(count):
        await connection.send(make_payload(seq))
        if (seq + 1) % 100 == 0 or seq + 1 == count:
            print(f"[ping] sent {seq + 1}/{count}")
        await asyncio.sleep(interval_ms / 1000.0)

    await asyncio.sleep(0.2)   # let the last frame flush out of the router
    router_task.cancel()


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="CSP ping generator (SRS-4 shell wrapper)")
    ap.add_argument("-c", dest="count", type=int, default=5, help="number of pings")
    ap.add_argument("-i", dest="interval", type=float, default=100,
                    help="interval between pings (assumed ms; lower = faster)")
    args = ap.parse_args()
    asyncio.run(main(args.count, args.interval))